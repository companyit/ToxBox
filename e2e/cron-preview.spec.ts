import { expect, hydrated, origin, test } from './helpers'

test('从目录找到 Cron，在手机宽度下选择或输入起点并预览', async ({ page }) => {
  const outbound: string[] = []
  page.on('request', request => {
    if (!request.url().startsWith(origin + '/')) outbound.push(request.url())
  })
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto('/')
  await hydrated(page)
  await page.getByLabel('搜索工具', { exact: true }).fill('Cron')
  await Promise.all([
    page.waitForURL('**/developer/cron-preview/', { waitUntil: 'load' }),
    page.getByRole('link', { name: '打开工具 ：Cron 执行时间预览', exact: true }).click(),
  ])
  await hydrated(page)

  const expression = page.getByLabel('Cron 表达式')
  const start = page.getByLabel('起算时间（UTC）')
  const picker = page.getByLabel('选择起算时间')
  const times = page.getByRole('region', { name: '触发时间（UTC）' }).locator('time')
  await page.getByRole('button', { name: '填入示例' }).click()
  await expect(expression).toBeFocused()
  await expect(picker).toHaveValue('2026-11-20T09:00')
  await expression.press('Enter')
  await expect(times).toHaveCount(10)
  await expect(times.first()).toHaveText('2026-11-23 09:00')
  await picker.fill('2026-11-20T08:59')
  await expect(start).toHaveValue('2026-11-20 08:59')
  await expect(times).toHaveCount(0)
  await page.getByRole('button', { name: '预览触发时间' }).click()
  await expect(times.first()).toHaveText('2026-11-20 09:00')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  expect(outbound).toEqual([])
})

test('错误、无结果及不足十项状态保留输入，清空后回焦', async ({ page }) => {
  await page.goto('/developer/cron-preview/')
  await hydrated(page)
  const expression = page.getByLabel('Cron 表达式')
  const start = page.getByLabel('起算时间（UTC）')
  const run = page.getByRole('button', { name: '预览触发时间' })
  const status = page.locator('#cron-status')
  await expression.fill('60 9 * * *')
  await start.fill('2026-11-21 00:00')
  await run.click()
  await expect(status).toContainText('分钟字段')
  await expect(expression).toHaveValue('60 9 * * *')
  await expression.fill('0 9 31 2 *')
  await run.click()
  await expect(status).toContainText('没有匹配')
  await expression.fill('* * * * *')
  await start.fill('9999-12-31 23:58')
  await run.click()
  await expect(status).toContainText('仅找到 1 次')
  await page.getByRole('button', { name: '清空' }).click()
  await expect(expression).toBeFocused()
  await expect(start).toHaveValue('')
  await expect(status).toHaveText('')
})

test('可视化生成常用计划，复用 UTC 预览并继续手输', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto('/developer/cron-preview/')
  await hydrated(page)
  const expression = page.getByLabel('Cron 表达式')
  const status = page.locator('#cron-status')
  const results = page.getByRole('region', { name: '触发时间（UTC）' }).locator('time')
  await page.getByText('可视化生成 Cron 表达式', { exact: true }).press('Enter')
  const schedule = page.getByLabel('执行计划')
  const generate = page.getByRole('button', { name: '生成表达式' })
  await generate.click()
  await expect(expression).toHaveValue('0 9 * * 1-5')
  await expect(status).toContainText('填写 UTC 起算时间')
  await page.getByLabel('起算时间（UTC）').fill('2026-11-20 09:00')
  await generate.press('Enter')
  await expect(results.first()).toHaveText('2026-11-23 09:00')

  await schedule.selectOption('weekly')
  await page.getByRole('checkbox', { name: '周一' }).uncheck()
  await generate.click()
  await expect(status).toContainText('至少选择一个')
  await expect(expression).toHaveValue('0 9 * * 1-5')
  await page.getByRole('checkbox', { name: '周日' }).check()
  await page.getByRole('checkbox', { name: '周三' }).check()
  await page.getByLabel('执行时间（UTC）').fill('08:30')
  await generate.click()
  await expect(expression).toHaveValue('30 8 * * 0,3')
  await expect(results.first()).toHaveText('2026-11-22 08:30')

  await schedule.selectOption('minute-step')
  await page.getByLabel('分钟步长').fill('17')
  await generate.click()
  await expect(expression).toHaveValue('*/17 * * * *')
  await expect(results.first()).toHaveText('2026-11-20 09:17')
  await expression.fill('0 10 * * *')
  await expect(results).toHaveCount(0)
  await page.getByRole('button', { name: '预览触发时间' }).click()
  await expect(results.first()).toHaveText('2026-11-20 10:00')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
})
