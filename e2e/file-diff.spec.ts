import { test, expect, hydrated } from './helpers'
for(const width of [375,768,1440]) test(`FD 文件本地读取、逐行对比与清理 ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:900});const requests:string[]=[];page.on('request',r=>requests.push(r.url()))
 await page.goto('/');await hydrated(page)
 await Promise.all([page.waitForURL('**/office/file-diff/'), page.getByRole('link',{name:'打开工具 ：文件对比',exact:true}).click()]);await hydrated(page)
 const old=page.getByLabel('原文件',{exact:true}),fresh=page.getByLabel('新文件',{exact:true}),run=page.getByRole('button',{name:'开始对比',exact:true})
 const storage=await page.evaluate(()=>[JSON.stringify(localStorage),JSON.stringify(sessionStorage)])
 await old.setInputFiles({name:'PRIVATE_FILE_045.TXT',mimeType:'text/plain',buffer:Buffer.from('\uFEFF准备资料\r\n校对内容\r\n发送邮件')})
 await fresh.setInputFiles({name:'new.md',mimeType:'text/plain',buffer:Buffer.from('准备资料\n补充配图\n发送邮件')})
 await expect(page.getByLabel('原文件预览（只读）',{exact:true})).toHaveValue('准备资料\n校对内容\n发送邮件')
 await expect(run).toBeEnabled();await run.click()
 await expect(page.locator('.diff-summary')).toHaveText('新增 1 行 · 删除 1 行 · 保留 2 行')
 await page.getByLabel('仅看变化',{exact:true}).check();await expect(page.locator('tbody tr')).toHaveCount(2)
 await page.getByRole('button',{name:'查看完整报告',exact:true}).click()
 await expect(page.getByLabel('对比报告（只读）',{exact:true})).not.toHaveValue(/PRIVATE_FILE/)
 await page.getByRole('button',{name:'交换文件',exact:true}).click();await expect(page.locator('.diff-result')).toHaveCount(0)
 await run.click();await expect(page.locator('.diff-add')).toContainText('校对内容')
 await old.setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from([0xff,0xfe,65,0])})
 await expect(page.locator('#file-status-before')).toContainText('UTF-8');await expect(run).toBeDisabled()
 await expect(page.getByLabel('新文件预览（只读）',{exact:true})).toHaveValue('准备资料\n校对内容\n发送邮件')
 await old.setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from('')})
 await fresh.setInputFiles({name:'empty.json',mimeType:'application/json',buffer:Buffer.from('')})
 await expect(run).toBeEnabled();await run.click();await expect(page.locator('.diff-summary')).toHaveText('新增 0 行 · 删除 0 行 · 保留 0 行')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('button',{name:'清空',exact:true}).click();await expect(page.getByRole('button',{name:'选择原文件',exact:true})).toBeFocused()
 expect(requests.some(url=>/PRIVATE_FILE|googletagmanager|google-analytics|adsbygoogle/.test(url))).toBe(false)
 expect(await page.evaluate(()=>[JSON.stringify(localStorage),JSON.stringify(sessionStorage)])).toEqual(storage)
 await page.screenshot({path:info.outputPath(`file-diff-${width}.png`),fullPage:true})
 await page.reload();await hydrated(page);await expect(run).toBeDisabled()
 await expect(page.getByLabel('原文件预览（只读）',{exact:true})).toHaveValue('')
})

for(const width of [375,768,1440]) test(`FDO 5000行/50万码元、200行分页与完整报告 ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:900})
 await page.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:()=>Promise.reject(new Error('synthetic clipboard failure'))}}))
 await page.goto('/office/file-diff/');await hydrated(page)
 const left=Array.from({length:5000},(_,i)=>'a'.repeat(94)+String(i).padStart(5,'0')).join('\n')+'a'
 const right=Array.from({length:5000},(_,i)=>'b'.repeat(94)+String(i).padStart(5,'0')).join('\n')+'b'
 const old=page.getByLabel('原文件',{exact:true}),fresh=page.getByLabel('新文件',{exact:true}),run=page.getByRole('button',{name:'开始对比',exact:true})
 await old.setInputFiles({name:'left.txt',mimeType:'text/plain',buffer:Buffer.from(left)})
 await fresh.setInputFiles({name:'right.txt',mimeType:'text/plain',buffer:Buffer.from(right)})
 await expect(run).toBeEnabled();const start=Date.now();await run.click()
 await expect(page.locator('.diff-summary')).toHaveText('新增 5000 行 · 删除 5000 行 · 保留 0 行')
 const duration=Date.now()-start
 await expect(page.locator('tbody tr')).toHaveCount(200)
 await expect(page.locator('.pagination')).toContainText('第 1 / 50 页')
 await expect(page.locator('#diff-report')).toHaveCount(0)
 await page.getByRole('button',{name:'下一页',exact:true}).click()
 await expect(page.locator('tbody tr').first().locator('td').nth(1)).toHaveText('201')
 await page.getByRole('button',{name:'查看完整报告',exact:true}).click()
 const report=page.getByLabel('对比报告（只读）',{exact:true})
 expect((await report.inputValue()).split('\n')).toHaveLength(10003)
 expect(await report.inputValue()).toContain('- 删除\t5000\t—\t'+left.split('\n')[4999])
 expect(await report.inputValue()).toContain('+ 新增\t—\t5000\t'+right.split('\n')[4999])
 await page.getByRole('button',{name:'复制对比报告',exact:true}).click()
 await expect(page.locator('#diff-status')).toContainText('手动复制');await expect(report).toBeFocused()
 await page.getByLabel('仅看变化',{exact:true}).check()
 await expect(page.locator('#diff-report')).toHaveCount(0);await expect(page.locator('.pagination')).toContainText('第 1 / 50 页')
 await page.evaluate(()=>document.documentElement.style.fontSize='200%')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.evaluate(()=>document.documentElement.style.fontSize='')
 await old.setInputFiles({name:'left.txt',mimeType:'text/plain',buffer:Buffer.from(left)})
 await expect(run).toBeEnabled();await run.click();await expect(page.locator('.diff-summary')).toContainText('删除 5000 行')
 await old.setInputFiles({name:'too-many-lines.txt',mimeType:'text/plain',buffer:Buffer.from('x\n'.repeat(5000))})
 await expect(page.locator('#file-status-before')).toContainText('5,000 行');await expect(run).toBeDisabled()
 await old.setInputFiles({name:'too-long.txt',mimeType:'text/plain',buffer:Buffer.from('x'.repeat(500001))})
 await expect(page.locator('#file-status-before')).toContainText('500,000')
 await old.setInputFiles({name:'too-big.txt',mimeType:'text/plain',buffer:Buffer.alloc(2*1024*1024+1,120)})
 await expect(page.locator('#file-status-before')).toContainText('2 MiB')
 await old.setInputFiles({name:'restored.txt',mimeType:'text/plain',buffer:Buffer.from('甲\n乙')})
 await fresh.setInputFiles({name:'new.txt',mimeType:'text/plain',buffer:Buffer.from('甲\n丙')})
 await expect(run).toBeEnabled();await run.focus();await page.keyboard.press('Enter')
 await expect(page.locator('.diff-summary')).toHaveText('新增 1 行 · 删除 1 行 · 保留 1 行')
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.screenshot({path:info.outputPath(`file-diff-expanded-${width}.png`),fullPage:true})
 await info.attach('5000-line-500000-code-unit-timing',{body:JSON.stringify({width,durationMs:duration,kind:'button-to-summary including worker and initial rendering; desktop viewport only'}),contentType:'application/json'})
})
