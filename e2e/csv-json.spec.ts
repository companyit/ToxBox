    await page.getByRole('button', { name: '填入示例', exact: true }).click()
    await expect(input).toHaveValue(source)
    await expect(page.locator('#table-status')).toContainText('请先清空')
    await page.getByLabel('转换方向', { exact: true }).selectOption('json-to-csv')
    await expect(result).toHaveValue('')
    await input.fill(JSON.stringify(values))
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(result).toHaveValue('"001","甲,乙"\n"002","他说""好""\n第二行"')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
