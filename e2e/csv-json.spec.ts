    await input.fill('[[1]]')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(result).toHaveValue('"1"')
    await input.fill('[1,,2]')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(page.locator('#table-status')).toContainText('JSON 语法无效')
    await expect(input).toHaveValue('[1,,2]'); await expect(result).toHaveValue('')
    await input.fill('[]')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(page.locator('#table-status')).toContainText('结果为空。 0 条记录，0 列。')
    await expect(page.getByRole('button', { name: '复制结果', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '清空', exact: true }).click()
    await expect(input).toBeFocused(); await expect(input).toHaveValue('')
    await expect(page.getByLabel('转换方向', { exact: true })).toHaveValue('csv-to-json')
    await input.fill('"unclosed')
