import { test, expect, hydrated } from './helpers'
for (const width of [375, 768, 1440]) {
  test(`TABLE 双向转换、多行引号及错误保留 ${width}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/office/csv-json/'); await hydrated(page)
    await expect(page.locator('.site-header nav a[href="/office/"]')).toHaveAttribute('aria-current', 'page')
    const input = page.getByLabel('待转换的表格文本', { exact: true }), result = page.getByLabel('表格结果（只读）', { exact: true })
    const source = '001,"甲,乙"\n002,"他说""好""\n第二行"'
    const values = [['001', '甲,乙'], ['002', '他说"好"\n第二行']]
    await input.fill(source)
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(result).toHaveValue(JSON.stringify(values, null, 2))
    await expect(input).toHaveValue(source)
    await expect(page.locator('#table-status')).toContainText('2 条记录，2 列')
    await page.getByRole('button', { name: '填入示例', exact: true }).click()
    await expect(input).toHaveValue(source)
    await expect(page.locator('#table-status')).toContainText('请先清空')
    await page.getByLabel('转换方向', { exact: true }).selectOption('json-to-csv')
    await expect(result).toHaveValue('')
    await input.fill(JSON.stringify(values))
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(result).toHaveValue('"001","甲,乙"\n"002","他说""好""\n第二行"')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await info.attach(`csv-json-${width}`, { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' })
    await input.fill('[[1]]')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(page.locator('#table-status')).toContainText('非字符串字段')
    await expect(input).toHaveValue('[[1]]'); await expect(result).toHaveValue('')
    await input.fill('[]')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(page.locator('#table-status')).toContainText('结果为空。 0 条记录，0 列。')
    await expect(page.getByRole('button', { name: '复制结果', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '清空', exact: true }).click()
    await expect(input).toBeFocused(); await expect(input).toHaveValue('')
    await expect(page.getByLabel('转换方向', { exact: true })).toHaveValue('csv-to-json')
    await input.fill('"unclosed')
    await page.getByRole('button', { name: '转换表格', exact: true }).click()
    await expect(page.locator('#table-status')).toContainText('CSV 引号格式无效')
    await expect(input).toHaveValue('"unclosed')
    await page.reload(); await hydrated(page); await expect(input).toHaveValue('')
  })
}
test('TABLE 键盘/组合输入、超限、复制失败与离页清理', async ({ page, browserName }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(Error('denied')) } }))
  await page.goto('/office/csv-json/'); await hydrated(page)
  const input = page.getByLabel('待转换的表格文本', { exact: true }), result = page.getByLabel('表格结果（只读）', { exact: true })
  await input.focus(); await page.keyboard.type('001,true')
  await input.dispatchEvent('compositionstart')
  await expect(page.getByRole('button', { name: '转换表格', exact: true })).toBeDisabled()
  await expect(page.getByLabel('转换方向', { exact: true })).toBeDisabled()
  await input.dispatchEvent('compositionend')
  await page.keyboard.press(browserName === 'webkit' && process.platform === 'darwin' ? 'Alt+Tab' : 'Tab')
  await expect(page.getByRole('button', { name: '转换表格', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(result).toHaveValue(JSON.stringify([['001', 'true']], null, 2))
  await page.getByRole('button', { name: '复制结果', exact: true }).click()
  await expect(page.locator('#table-status')).toContainText('手动复制'); await expect(result).toBeFocused()
  await input.fill('x'.repeat(100001))
  await page.getByRole('button', { name: '转换表格', exact: true }).click()
  await expect(page.locator('#table-status')).toContainText('输入超过')
  expect((await input.inputValue()).length).toBe(100001)
  await expect(result).toHaveValue('')
  await page.evaluate(() => window.dispatchEvent(new PageTransitionEvent('pagehide', { persisted: true })))
  await expect(input).toHaveValue(''); await expect(page.locator('#table-status')).toHaveText('')
})
test('TABLE 搜索、办公入口、文本绑定与内容不写 URL/存储/请求', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => requests.push(request.url()))
  await page.goto('/'); await hydrated(page)
  await page.getByLabel('搜索工具', { exact: true }).fill('CSV')
  await expect(page.locator('.tool-grid li')).toHaveCount(1)
  await page.getByRole('link', { name: '试用工具 ：CSV 与 JSON 表格互转', exact: true }).click(); await hydrated(page)
  const originalStorage = await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])
  const marker = 'TABLE_PRIVATE_019'
  const input = page.getByLabel('待转换的表格文本', { exact: true }), result = page.getByLabel('表格结果（只读）', { exact: true })
  await page.getByLabel('转换方向', { exact: true }).selectOption('json-to-csv')
  await input.fill(JSON.stringify([['<img src=x onerror=alert(1)>', marker]]))
  await page.getByRole('button', { name: '转换表格', exact: true }).click()
  expect(await result.inputValue()).toContain(marker)
  await expect(page.locator('main img')).toHaveCount(0)
  expect(page.url()).toBe('http://127.0.0.1:4177/office/csv-json/')
  expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])).toEqual(originalStorage)
  expect(requests.every(url => !url.includes(marker))).toBe(true)
  await page.getByRole('link', { name: '办公工具', exact: true }).first().click(); await hydrated(page)
  await page.getByRole('link', { name: '试用工具 ：CSV 与 JSON 表格互转', exact: true }).click(); await hydrated(page)
  await expect(input).toHaveValue(''); await expect(result).toHaveValue('')
})
