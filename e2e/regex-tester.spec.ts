import { expect, hydrated, origin, test } from './helpers'

test('正则匹配与捕获组、键盘分页及敏感隔离', async ({ page }) => {
  const external: string[] = []
  await page.route('**/*', route => {
    const url = route.request().url()
    if (url.startsWith(origin + '/')) return route.continue()
    external.push(url)
    return route.abort()
  })
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto('/')
  await hydrated(page)
  await page.evaluate(() => Reflect.set(window, 'regexDocumentProbe', true))
  await page.getByLabel('搜索工具', { exact: true }).fill('正则表达式测试')
  await Promise.all([
    page.waitForURL('**/developer/regex-tester/', { waitUntil: 'load' }),
    page.getByRole('link', { name: '打开工具 ：正则表达式测试', exact: true }).click(),
  ])
  await hydrated(page)
  expect(await page.evaluate(() => Reflect.get(window, 'regexDocumentProbe'))).toBeUndefined()
  const pattern = page.getByLabel('正则表达式', { exact: true })
  const sample = page.getByLabel('样本文本', { exact: true })
  const status = page.locator('#regex-status')
  const mobilePattern = (await pattern.boundingBox())!
  expect((await sample.boundingBox())!.y).toBeGreaterThan(mobilePattern.y + mobilePattern.height)
  await expect(pattern).toHaveAttribute('rows', '4')
  await page.setViewportSize({ width: 1440, height: 900 })
  const desktopPattern = (await pattern.boundingBox())!
  expect((await sample.boundingBox())!.x).toBeGreaterThan(desktopPattern.x + desktopPattern.width)
  await page.setViewportSize({ width: 375, height: 900 })
  const run = page.getByRole('button', { name: '测试匹配', exact: true })
  await pattern.fill('(?<id>X)(a?)(z)?')
  await sample.fill('😀x')
  await page.getByRole('checkbox', { name: /忽略大小写/ }).check()
  await run.press('Enter')
  const output = page.getByRole('region', { name: '匹配结果' })
  await expect(output).toContainText('位置 2 至 3')
  await expect(output.getByText('id', { exact: true })).toBeVisible()
  await expect(output).toContainText('空字符串')
  await expect(output).toContainText('未参与匹配')
  await pattern.fill('.')
  await expect(output).toHaveCount(0)
  await sample.fill('x'.repeat(501))
  await run.click()
  await expect(status).toContainText('仅预览前 500 项')
  const pagination = page.getByRole('navigation', { name: '匹配结果分页' })
  expect((await pagination.boundingBox())!.y).toBeLessThan((await output.locator('ol').boundingBox())!.y)
  await page.getByRole('button', { name: '下一页' }).press('Enter')
  await expect(status).toContainText('第 2 / 10 页')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex/)
  expect(external).toEqual([])
})

test('Worker 超时、取消和离页后可继续使用', async ({ page }) => {
  // Exercise the real browser Worker lifecycle without depending on engine-specific regex optimizations.
  let stalledJobs = 0
  await page.route(/\/assets\/regexTester\.worker-[^/]+\.js$/, route => {
    if (stalledJobs++ >= 2) return route.continue()
    return route.fulfill({ contentType: 'text/javascript', body: 'self.onmessage = () => {}' })
  })
  await page.goto('/developer/regex-tester/')
  await hydrated(page)
  const pattern = page.locator('#regex-pattern')
  const sample = page.locator('#regex-sample')
  const run = page.getByRole('button', { name: '测试匹配', exact: true })
  const status = page.locator('#regex-status')
  await pattern.fill('a')
  await sample.fill('样本!')
  await run.click()
  await expect(status).toHaveText('正在匹配…')
  await expect.poll(() => stalledJobs).toBe(1)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(status).toHaveText('已取消匹配。')
  await run.click()
  await expect(status).toHaveText('匹配超过 2 秒，已停止。')
  await expect(sample).toHaveValue('样本!')
  await pattern.fill('[')
  await run.click()
  await expect(status).toContainText('语法无效')
  await pattern.fill('!')
  await run.click()
  await expect(status).toContainText('共 1 项匹配')
  await page.evaluate(() => window.dispatchEvent(new Event('pagehide')))
  await expect(pattern).toHaveValue('')
  await expect(sample).toHaveValue('')
  await expect(status).toHaveText('')
})
