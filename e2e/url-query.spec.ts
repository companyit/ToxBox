import { expect, hydrated, test } from './helpers'

test('URL 参数发现、严格解析、模式切换及敏感隔离', async ({ page }) => {
  const external: string[] = []
  await page.route('**/*', route => {
    const url = route.request().url()
    if (url.startsWith('http://127.0.0.1:4177/')) return route.continue()
    external.push(url)
    return route.abort()
  })
  await page.goto('/')
  await hydrated(page)
  await page.evaluate(() => { Reflect.set(window, 'urlQueryDocumentProbe', true) })
  await page.getByLabel('搜索工具', { exact: true }).fill('URL 参数解析')
  await Promise.all([
    page.waitForURL('**/developer/url-query/', { waitUntil: 'load' }),
    page.getByRole('link', { name: '打开工具 ：URL 参数解析', exact: true }).click(),
  ])
  await hydrated(page)
  expect(await page.evaluate(() => Reflect.get(window, 'urlQueryDocumentProbe'))).toBeUndefined()
  const source = page.getByLabel('待解析内容')
  const parse = page.getByRole('button', { name: '解析参数' })
  const data = 'https://example.test/?x=a+b&x=%2B&flag&empty=&=value#ignored'
  await source.fill(data)
  await parse.click()
  const rows = page.locator('tbody tr')
  await expect(rows).toHaveCount(5)
  await expect(rows.nth(0)).toContainText('a+b')
  await expect(rows.nth(2)).toContainText('无等号')
  await expect(rows.nth(3)).toContainText('空值')
  await expect(rows.nth(4)).toContainText('空名称')
  await page.getByRole('checkbox').check()
  await expect(rows).toHaveCount(0)
  await parse.click()
  await expect(rows.nth(0)).toContainText('a b')
  await expect(rows.nth(1)).toContainText('+')
  await expect(source).toHaveValue(data)
  await source.fill('https://example.test/?private=%FF')
  await parse.click()
  await expect(page.getByRole('status')).toContainText('第 1 项')
  await expect(page.getByRole('status')).not.toContainText('private')
  await expect(source).toHaveValue('https://example.test/?private=%FF')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex/)
  expect(external).toHaveLength(0)
})

test('移动视口下使用键盘翻页，并在输入类型变化或清空后撤销结果', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 900 })
  await page.goto('/developer/url-query/')
  await hydrated(page)
  const source = page.getByLabel('待解析内容')
  const mode = page.getByLabel('输入类型')
  await mode.selectOption('query')
  await expect(page.locator('#query-help')).toContainText('?name=value')
  await source.fill(Array.from({ length: 51 }, (_, index) => 'name=' + index).join('&') + 'x'.repeat(500))
  await page.getByRole('button', { name: '解析参数' }).press('Enter')
  await expect(page.locator('tbody tr')).toHaveCount(50)
  const pagination = page.getByRole('navigation', { name: '参数结果分页' })
  expect((await pagination.boundingBox())!.y).toBeLessThan((await page.locator('table').boundingBox())!.y)
  await page.getByRole('button', { name: '下一页' }).press('Enter')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByRole('status')).toContainText('第 2 / 2 页')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await page.getByRole('button', { name: '上一页' }).press('Enter')
  await expect(page.getByRole('status')).toContainText('第 1 / 2 页')
  await mode.selectOption('url')
  await expect(page.locator('table')).toHaveCount(0)
  await page.getByRole('button', { name: '清空' }).click()
  await expect(source).toHaveValue('')
})
