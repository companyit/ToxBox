test('后台恢复按实际时间重算，并清除旧复制提示', async () => {
  vi.useFakeTimers(); vi.setSystemTime(59000)
  vi.mocked(generateTotp).mockResolvedValue('287082')
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: vi.fn().mockResolvedValue(undefined) } })
  const wrapper = mount(TotpView)
  await wrapper.get<HTMLInputElement>('#totp-secret').setValue('MY'); await wrapper.get('form:not(.import-form)').trigger('submit'); await flushPromises()
  await wrapper.findAll('button').find(button => button.text() === '复制验证码')!.trigger('click'); await flushPromises()
  expect(wrapper.text()).toContain('验证码已复制')
  vi.mocked(generateTotp).mockResolvedValue('123456')
  vi.setSystemTime(120000)
  vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
  document.dispatchEvent(new Event('visibilitychange')); await flushPromises()
  expect(generateTotp).toHaveBeenLastCalledWith('MY', 120000, undefined, { algorithm: 'SHA-1', digits: 6, period: 30 })
  expect(wrapper.get('output').text()).toBe('123456')
  expect(wrapper.text()).not.toContain('验证码已复制')
  wrapper.unmount(); vi.restoreAllMocks()
})
