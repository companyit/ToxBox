test('链接导入原子更新参数、失败保留已有密钥且整体清空', async () => {
  vi.useFakeTimers(); vi.setSystemTime(59000)
  vi.mocked(generateTotp).mockResolvedValue('12345678')
  const wrapper = mount(TotpView)
  const uri = wrapper.get<HTMLInputElement>('#totp-uri')
  await uri.setValue('otpauth://totp/Example:alice?secret=MY&algorithm=SHA256&digits=8&period=60')
  await wrapper.get('.import-form').trigger('submit')
  expect(wrapper.get<HTMLInputElement>('#totp-secret').element.value).toBe('MY')
  expect(uri.element.value).toBe('')
  expect(wrapper.text()).toContain('SHA-256 · 8 位 · 60 秒')
  await wrapper.get('form:not(.import-form)').trigger('submit'); await flushPromises()
  expect(generateTotp).toHaveBeenLastCalledWith('MY', 59000, undefined, { algorithm: 'SHA-256', digits: 8, period: 60 })
  expect(wrapper.get('progress').attributes('max')).toBe('60')
  expect(wrapper.text()).toContain('剩余 1 秒')
  await uri.setValue('otpauth://hotp/private?secret=INVALID0')
  await wrapper.get('.import-form').trigger('submit')
  expect(wrapper.get<HTMLInputElement>('#totp-secret').element.value).toBe('MY')
  expect(wrapper.text()).toContain('SHA-256 · 8 位 · 60 秒')
  expect(wrapper.get('#totp-import-error').text()).not.toContain('INVALID0')
  await wrapper.findAll('button').find(button => button.text() === '清空')!.trigger('click')
  expect(uri.element.value).toBe('')
  expect(wrapper.text()).not.toContain('alice')
  expect(wrapper.text()).toContain('SHA-1 · 6 位 · 30 秒')
  wrapper.unmount()
})

