test('组合输入期间所有操作禁用且无结果，结束才转换', async () => {
  const w = setup()
  await w.get('#table-input').setValue('a,b')
  await w.get('button').trigger('click')
  await w.get('#table-input').trigger('compositionstart')
  expect(w.get('#table-direction').attributes()).toHaveProperty('disabled')
  for (const button of w.findAll('button')) expect(button.attributes()).toHaveProperty('disabled')
  await w.get('button').trigger('click')
  expect(w.get('#table-result').element).toHaveProperty('value', '')
  await w.get('#table-input').trigger('compositionend')
  await w.get('button').trigger('click')
  expect(w.get('#table-status').text()).toContain('转换完成')
})
test('复制 Promise 完成才提示，换向/编辑/pagehide 使迟到成功或失败失效', async () => {
  vi.stubGlobal('isSecureContext', true)
  let resolve!: () => void, reject!: () => void
  const writeText = vi.fn(() => new Promise<void>((done, fail) => { resolve = done; reject = () => fail(Error()) }))
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText } })
  const w = setup()
  await w.get('#table-input').setValue('a')
  await w.get('button').trigger('click')
  await w.findAll('button')[3]!.trigger('click')
  expect(writeText).toHaveBeenCalledWith(JSON.stringify([['a']], null, 2))
  expect(w.get('#table-status').text()).not.toContain('已复制')
  resolve(); await flushPromises()
  expect(w.get('#table-status').text()).toContain('结果已复制')
  await w.findAll('button')[3]!.trigger('click')
  await w.get('#table-direction').setValue('json-to-csv')
  resolve(); await flushPromises()
  expect(w.get('#table-status').text()).toBe('')
  await w.get('#table-input').setValue('[["b"]]')
  await w.get('button').trigger('click')
  await w.findAll('button')[3]!.trigger('click')
  await w.get('#table-input').setValue('[]')
  reject(); await flushPromises()
  expect(w.get('#table-status').text()).toBe('')
  await w.get('#table-input').setValue('[["b"]]')
  await w.get('button').trigger('click')
  await w.findAll('button')[3]!.trigger('click')
  window.dispatchEvent(new Event('pagehide')); await nextTick()
  resolve(); await flushPromises()
  expect(w.get('#table-status').text()).toBe('')
  expect(w.get('#table-input').element).toHaveProperty('value', '')
  expect(w.get('#table-result').element).toHaveProperty('value', '')
})
test('复制失败选中结果，卸载后不更新反馈且新实例为空', async () => {
  vi.stubGlobal('isSecureContext', true)
  let resolve!: () => void
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => Promise.reject(Error()) } })
  const w = setup()
  await w.get('#table-input').setValue('a')
  await w.get('button').trigger('click')
  await w.findAll('button')[3]!.trigger('click'); await flushPromises()
  expect(w.get('#table-status').text()).toContain('手动复制')
  expect(document.activeElement).toBe(w.get('#table-result').element)
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: () => new Promise<void>(done => { resolve = done }) } })
  await w.findAll('button')[3]!.trigger('click')
  w.unmount(); wrappers.splice(wrappers.indexOf(w), 1)
  resolve(); await flushPromises()
  const fresh = setup()
  expect(fresh.get('#table-input').element).toHaveProperty('value', '')
  expect(fresh.get('#table-status').text()).toBe('')
})
