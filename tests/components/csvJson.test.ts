import { afterEach, expect, test, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { nextTick, ref } from 'vue'
import CsvJsonPage from '../../src/views/pages/CsvJsonPage.vue'
import { interactionReadyKey } from '../../src/interactionReady'

const wrappers: ReturnType<typeof mount>[] = []
function setup() {
  const wrapper = mount(CsvJsonPage, { attachTo: document.body, global: { provide: { [interactionReadyKey as symbol]: ref(true) }, stubs: { RouterLink: { template: '<a><slot /></a>' } } } })
  wrappers.push(wrapper)
  return wrapper
}
afterEach(() => { wrappers.forEach(wrapper => wrapper.unmount()); wrappers.length = 0; vi.unstubAllGlobals() })
test('两方向转换保留输入，切换/编辑撤销结果及记录列数，空表格明确播报', async () => {
  const w = setup()
  await w.get('#table-input').setValue('001,"甲,乙"')
  await w.get('button').trigger('click')
  expect(JSON.parse((w.get('#table-result').element as HTMLTextAreaElement).value)).toEqual([['001', '甲,乙']])
  expect(w.get('#table-status').text()).toContain('1 条记录，2 列')
  expect(w.get('#table-input').element).toHaveProperty('value', '001,"甲,乙"')
  await w.get('#table-direction').setValue('json-to-csv')
  expect(w.get('#table-result').element).toHaveProperty('value', '')
  expect(w.get('#table-status').text()).toBe('')
  await w.get('#table-input').setValue('[["001", "a"]]')
  await w.get('button').trigger('click')
  expect(w.get('#table-result').element).toHaveProperty('value', '"001","a"')
  await w.get('#table-input').setValue('[]')
  expect(w.get('#table-result').element).toHaveProperty('value', '')
  await w.get('button').trigger('click')
  expect(w.get('#table-status').text()).toContain('结果为空。 0 条记录，0 列。')
  expect(w.findAll('button')[3]!.attributes()).toHaveProperty('disabled')
  await w.get('#table-input').setValue('')
  await w.get('button').trigger('click')
  expect(w.get('#table-status').text()).toBe('暂无内容。')
})
